func dockerOSTypeVerdict(raw string) (status, message string) {
	normalized := strings.Join(strings.Fields(raw), " ")
	switch strings.ToLower(normalized) {
	case "linux":
		return "ok", "docker is in Linux-container mode"
	case "windows":
		return "fail", "docker is in Windows-container mode; ContainerBin runs Linux images only — switch to Linux containers from the Docker Desktop tray menu"
	default:
		if normalized == "" {
			return "warn", "container mode could not be determined"
		}
		return "warn", "unrecognized container mode: " + normalized
	}
}

func doctor(reg Registry, cfgPath string) error {
	failures := 0
	warnings := 0
	ok := func(format string, args ...any) { fmt.Printf("OK       "+format+"\n", args...) }
	warn := func(format string, args ...any) { warnings++; fmt.Printf("WARN     "+format+"\n", args...) }
	fail := func(format string, args ...any) { failures++; fmt.Printf("FAIL     "+format+"\n", args...) }

	dockerPath, err := exec.LookPath("docker")
	if err != nil {
		fail("Docker CLI not found in PATH")
	} else {
		ok("Docker CLI: %s", dockerPath)
		cmd := exec.Command("docker", "version", "--format", "{{.Server.Version}}")
		out, err := cmd.Output()
		if err != nil {
			fail("Docker engine unreachable: %v", err)
		} else {
			ok("Docker engine: %s", strings.TrimSpace(string(out)))
			cmd = exec.Command("docker", "info", "--format", "{{.OSType}}")
			out, err = cmd.Output()
			if err != nil {
				warn("docker info failed: %v", err)
			} else {
				status, msg := dockerOSTypeVerdict(string(out))
				switch status {
				case "ok":
					ok("%s", msg)
				case "warn":
					warn("%s", msg)
				case "fail":
					fail("%s", msg)
				}
			}
		}
	}

	if reg.SchemaVersion != 1 {
		fail("registry schema=%d (supported=1)", reg.SchemaVersion)
	} else {
		ok("registry schema 1: %s", cfgPath)
	}

	lf, lockPath, err := loadLockFileForRegistry()
	if err != nil {
		fail("lockfile invalid: %v", err)
	} else if lf == nil {
		warn("lockfile missing: %s (runtime is UNLOCKED)", lockPath)
	} else {
		missing := 0
		for _, image := range configuredImages(reg) {
			e, found := lf.Images[image]
			if !found {
				missing++
				continue
			}
			if exec.Command("docker", "image", "inspect", e.Resolved).Run() != nil {
				missing++
			}
		}
		if missing == 0 {
			ok("lockfile complete and exact images local: %s", lockPath)
		} else {
			fail("lockfile has %d missing/unavailable image(s); run `cb lock --check`", missing)
		}
	}

	exe, _ := os.Executable()
	exe, _ = filepath.Abs(exe)
	dir := filepath.Dir(exe)
	pathParts := filepath.SplitList(os.Getenv("PATH"))
	inPath := false
	for _, part := range pathParts {
		if strings.EqualFold(strings.TrimRight(part, `\\/`), strings.TrimRight(dir, `\\/`)) {
			inPath = true
			break
		}
	}
	if inPath {
		ok("shim directory is in PATH: %s", dir)
	} else {
		fail("shim directory is not in PATH: %s", dir)
	}

	shimProblems := 0
	for name := range reg.Tools {
		shim := filepath.Join(dir, name+".exe")
		a, e1 := os.Stat(exe)
		b, e2 := os.Stat(shim)
		if e1 != nil || e2 != nil {
			shimProblems++
			continue
		}
		if !os.SameFile(a, b) {
			warn("shim %s is a copy, not a hardlink", name)
		}
	}
	if shimProblems == 0 {
		ok("all %d registry shims exist", len(reg.Tools))
	} else {
		fail("%d registry shim(s) missing; run `cb install`", shimProblems)
	}

	if runtime.GOOS == "windows" {
		out, _ := exec.Command("where.exe", "python").Output()
		// where.exe prints one full path per line; paths may contain spaces,
		// so this must split on newlines, never on whitespace.
		var lines []string
		for _, l := range strings.Split(strings.ReplaceAll(string(out), "\r", ""), "\n") {
			if l = strings.TrimSpace(l); l != "" {
				lines = append(lines, l)
			}
		}
		if len(lines) > 0 && strings.EqualFold(filepath.Clean(lines[0]), filepath.Join(dir, "python.exe")) {
			ok("python resolves to container-bin first")
		} else {
			warn("python does not resolve to container-bin first: %s", strings.TrimSpace(string(out)))
		}
		// Scan every result: the alias warning matters most when the
		// WindowsApps stub is the FIRST match (i.e. it wins over the shim).
		for _, line := range lines {
			if strings.Contains(strings.ToLower(line), `microsoft\windowsapps\python`) {
				warn("Windows App Execution Alias for python is present on PATH; disable it in Windows Settings > Apps > App execution aliases")
				break
			}
		}
	}

	managed, err := labeledManagedVolumes()
	if err != nil {
		warn("managed volume inspection failed: %v", err)
	} else {
		ok("managed labeled volumes inspectable: %d", len(managed))
	}

	fmt.Printf("\nDoctor summary: %d failure(s), %d warning(s)\n", failures, warnings)
	if failures > 0 {
		return fmt.Errorf("%d critical check(s) failed", failures)
	}
	return nil
}

func setupCommand(cfgPath string) error {
	if err := ensureRegistryFile(cfgPath); err != nil {
		return err
	}
	if err := appendMissingDefaultTools(cfgPath); err != nil {
		return err
	}
	reg, _, err := loadRegistry()
	if err != nil {
		return err
	}
	if err := installShims(reg); err != nil {
		return err
	}
	fmt.Println("\nRunning doctor after setup...")
	return doctor(reg, cfgPath)
}

func installShims(reg Registry) error {
	exe, err := os.Executable()
	if err != nil {
		return err
	}
	exe, err = filepath.Abs(exe)
	if err != nil {
		return err
	}
	dir := filepath.Dir(exe)
	names := make([]string, 0, len(reg.Tools))
	for name := range reg.Tools {
		names = append(names, name)
	}
	sort.Strings(names)
	for _, name := range names {
		dst := filepath.Join(dir, name+".exe")
		_ = os.Remove(dst)
		if err := os.Link(exe, dst); err != nil {
			if err := copyFile(exe, dst); err != nil {
				return fmt.Errorf("create %s: hardlink failed and copy fallback failed: %w", dst, err)
			}
			fmt.Printf("installed %-10s (copy fallback) -> %s\n", name, dst)
		} else {
			fmt.Printf("installed %-10s (hardlink)      -> %s\n", name, dst)
		}
	}
	fmt.Printf("\nRegistry:\n  %s\n\nAdd this directory near the front of PATH:\n  %s\n", filepath.Join(dir, "container-bin.toml"), dir)
	return nil
}

func copyFile(src, dst string) error {
	in, err := os.Open(src)
	if err != nil {
		return err
	}
	defer in.Close()
	out, err := os.OpenFile(dst, os.O_CREATE|os.O_WRONLY|os.O_TRUNC, 0755)
	if err != nil {
		return err
	}
	_, cpErr := io.Copy(out, in)
	closeErr := out.Close()
	if cpErr != nil {
		return cpErr
	}
	return closeErr
}

// interactiveTerminal is intentionally conservative: Docker gets a TTY only
// when both stdin and stdout are character devices. Pipes/redirection and
// process-captured output remain plain -i, preserving automation semantics.
func interactiveTerminal() bool {
	in, err := os.Stdin.Stat()
	if err != nil || in.Mode()&os.ModeCharDevice == 0 {
		return false
	}
	out, err := os.Stdout.Stat()
	return err == nil && out.Mode()&os.ModeCharDevice != 0
}

func runTool(t Tool, userArgs []string) (int, error) {
	cwd, err := os.Getwd()
	if err != nil {
		return 1, err
	}
	cwd, err = canonicalPath(cwd)
	if err != nil {
		return 1, err
	}
	root, found := findProjectRoot(cwd, projectMarkersFor(t))
	if !found {
		root = cwd
	}
	rel, err := filepath.Rel(root, cwd)
	if err != nil {
		return 1, err
	}
	workspaceRoot := workspaceRootFor(t, root)
	containerWD := workspaceRoot
	if rel != "." {
		containerWD += "/" + filepath.ToSlash(rel)
	}

	mappedUserArgs, pathMounts, err := mapToolArgs(t, root, cwd, workspaceRoot, userArgs)
	if err != nil {
		return 1, err
	}
	imageRef, err := runtimeImageForTool(t)
	if err != nil {
		return 1, err
	}
	args := []string{"run", "--rm", "-i"}
	if interactiveTerminal() {
		args = append(args, "-t")
	}
	args = append(args, "--workdir", containerWD)
	rootSpec, err := mountSpec("bind", root, workspaceRoot)
	if err != nil {
		return 1, err
	}
	args = append(args, "--mount", rootSpec)
	for _, m := range pathMounts {
		mount, err := mountSpec("bind", m.Source, m.Target)
		if err != nil {
			return 1, err
		}
		args = append(args, "--mount", mount)
	}
	for _, name := range selectedHostEnv(t) {
		args = append(args, "-e", name)
	}
	for _, kv := range t.EnvSet {
		args = append(args, "-e", kv)
	}

	switch t.Provider {
	case "python":
		envID := pythonEnvID(root, found)
		pyLabels := map[string]string{"cb.managed": "true", "cb.owner": "python313/venv"}
		if found {
			pyLabels["cb.kind"] = "project"
			pyLabels["cb.project_path"] = root
			pyLabels["cb.project_hash"] = volumeHash(root)
		} else {
			pyLabels["cb.kind"] = "compat"
		}
		venvSpec, err := mountSpec("volume", envID, "/venv")
		if err != nil {
			return 1, err
		}
		pipCacheSpec, err := mountSpec("volume", "cb-pip-cache", "/root/.cache/pip")
		if err != nil {
			return 1, err
		}
		if err := ensureManagedVolume(envID, pyLabels); err != nil {
			return 1, err
		}
		if err := ensureManagedVolume("cb-pip-cache", map[string]string{"cb.managed": "true", "cb.kind": "shared", "cb.owner": "python313/pip-cache"}); err != nil {
			return 1, err
		}
		args = append(args,
			"--mount", venvSpec,
			"--mount", pipCacheSpec,
			"-e", "VIRTUAL_ENV=/venv",
			"-e", "PATH=/venv/bin:/usr/local/bin:/usr/local/sbin:/usr/sbin:/usr/bin:/sbin:/bin",
		)
		args = append(args, imageRef)
		bootstrap := `if [ ! -x /venv/bin/python ]; then python -m venv /venv || exit $?; fi; if [ "$1" = "__CB_PIP__" ]; then shift; exec /venv/bin/python -m pip "$@"; else exec /venv/bin/python "$@"; fi`
		args = append(args, "sh", "-c", bootstrap, "cb")
		if t.Role == "pip" {
			args = append(args, "__CB_PIP__")
		}
		args = append(args, t.ArgsPrefix...)
		args = append(args, mappedUserArgs...)
	case "stateful":
		for _, spec := range t.ProjectVolumes {
			name, dst, err := parseVolumeBinding(spec)
			if err != nil {
				return 1, err
			}
			vol := statefulProjectVolumeID(t.StateGroup, name, root, found)
			dst = statefulWorkspaceDestination(dst, workspaceRoot)
			volSpec, err := mountSpec("volume", vol, dst)
			if err != nil {
				return 1, err
			}
			if err := ensureManagedVolume(vol, map[string]string{"cb.managed": "true", "cb.kind": "project", "cb.owner": t.StateGroup + "/" + name, "cb.project_path": root, "cb.project_hash": volumeHash(root)}); err != nil {
				return 1, err
			}
			args = append(args, "--mount", volSpec)
		}
		for _, spec := range t.SharedVolumes {
			name, dst, err := parseVolumeBinding(spec)
			if err != nil {
				return 1, err
			}
			vol := statefulSharedVolumeID(t.StateGroup, name)
			volSpec, err := mountSpec("volume", vol, dst)
			if err != nil {
				return 1, err
			}
			if err := ensureManagedVolume(vol, map[string]string{"cb.managed": "true", "cb.kind": "shared", "cb.owner": t.StateGroup + "/" + name}); err != nil {
				return 1, err
			}
			args = append(args, "--mount", volSpec)
		}
		args = append(args, imageRef)
		args = append(args, t.Command...)
		args = append(args, t.ArgsPrefix...)
		args = append(args, mappedUserArgs...)
	case "stateless":
		args = append(args, imageRef)
		args = append(args, t.Command...)
		args = append(args, t.ArgsPrefix...)
		args = append(args, mappedUserArgs...)
	default:
		return 1, fmt.Errorf("unsupported provider %q", t.Provider)
	}

	cmd := exec.Command("docker", args...)
	cmd.Stdin, cmd.Stdout, cmd.Stderr, cmd.Env = os.Stdin, os.Stdout, os.Stderr, os.Environ()
	err = cmd.Run()
	if err == nil {
		return 0, nil
	}
	var exitErr *exec.ExitError
	if errors.As(err, &exitErr) {
		return exitErr.ExitCode(), nil
	}
	return 1, err
}

type PathMount struct{ Source, Target string }

type pathMapper struct {
	root          string
	cwd           string
	workspaceRoot string
	mounts        []PathMount
	mountBySource map[string]string
}

// normalizeToolArgs repairs shell-level argv shapes that are unambiguous from
// the tool registry. In particular, PowerShell can hand native processes
// `-opt=` and its value as two argv elements. For path_equals options we join
// those back before path mapping, preserving the target tool's required syntax.
func normalizeToolArgs(t Tool, args []string) []string {
	out := make([]string, 0, len(args))
	for i := 0; i < len(args); i++ {
		arg := args[i]
		joined := false
		for _, opt := range t.PathEquals {
			prefix := opt + "="
			if arg == prefix && i+1 < len(args) {
				out = append(out, prefix+args[i+1])
				i++
				joined = true
				break
			}
		}
		if !joined {
			out = append(out, arg)
		}
	}
	return out
}

func traceTool(reg Registry, args []string) error {
	if len(args) == 0 {
		return errors.New("usage: cb trace TOOL [ARGS...]")
	}
	name := strings.ToLower(args[0])
	t, ok := reg.Tools[name]
	if !ok {
		return fmt.Errorf("no tool profile for %q", name)
	}
	cwd, err := os.Getwd()
	if err != nil {
		return err
	}
	cwd, err = canonicalPath(cwd)
	if err != nil {
		return err
	}
	root, found := findProjectRoot(cwd, projectMarkersFor(t))
	if !found {
		root = cwd
	}
	raw := append([]string(nil), args[1:]...)
	normalized := normalizeToolArgs(t, raw)
	workspaceRoot := workspaceRootFor(t, root)
	mapped, mounts, err := mapToolArgs(t, root, cwd, workspaceRoot, raw)
	if err != nil {
		return err
	}
	fmt.Printf("tool:       %s\n", t.Name)
	fmt.Printf("image:      %s\n", t.Image)
	fmt.Printf("provider:   %s\n", t.Provider)
	fmt.Printf("cwd:        %s\n", cwd)
	fmt.Printf("root:       %s\n", root)
	fmt.Printf("workspace:  %s\n", workspaceRoot)
	fmt.Printf("raw:        %#v\n", raw)
	fmt.Printf("normalized: %#v\n", normalized)
	fmt.Printf("mapped:     %#v\n", mapped)
	if len(mounts) == 0 {
		fmt.Printf("mounts:     (none beyond %s)\n", workspaceRoot)
	} else {
		fmt.Printf("mounts:     %#v\n", mounts)
	}
	fmt.Printf("path_equals: %#v\n", t.PathEquals)
	if t.Provider == "stateful" {
		fmt.Printf("state_group: %s\n", t.StateGroup)
		for _, spec := range t.ProjectVolumes {
			name, dst, _ := parseVolumeBinding(spec)
			dst = statefulWorkspaceDestination(dst, workspaceRoot)
			fmt.Printf("project_volume: %s -> %s\n", statefulProjectVolumeID(t.StateGroup, name, root, found), dst)
		}
		for _, spec := range t.SharedVolumes {
			name, dst, _ := parseVolumeBinding(spec)
			fmt.Printf("shared_volume:  %s -> %s\n", statefulSharedVolumeID(t.StateGroup, name), dst)
		}
	}
	return nil
}

func mapToolArgs(t Tool, root, cwd, workspaceRoot string, userArgs []string) ([]string, []PathMount, error) {
	normalized := normalizeToolArgs(t, userArgs)
	if runtime.GOOS != "windows" {
		return append([]string(nil), normalized...), nil, nil
	}
	pm := &pathMapper{root: root, cwd: cwd, workspaceRoot: workspaceRoot, mountBySource: map[string]string{}}
	mapped := append([]string(nil), normalized...)
	forceNext := false
	for i, arg := range normalized {
		if forceNext {
			v, err := pm.mapArg(arg, true)
			if err != nil {
				return nil, nil, err
			}
			mapped[i] = v
			forceNext = false
			continue
		}

		if containsString(t.PathNext, arg) {
			mapped[i] = arg
			forceNext = true
			continue
		}

		eqMapped := false
		for _, opt := range t.PathEquals {
			prefix := opt + "="
			if strings.HasPrefix(arg, prefix) {
				v, err := pm.mapArg(strings.TrimPrefix(arg, prefix), true)
				if err != nil {
					return nil, nil, err
				}
				mapped[i] = prefix + v
				eqMapped = true
				break
			}
		}
		if eqMapped {
			continue
		}

		lastEnabled := t.PathLast && (len(t.PathLastIfAny) == 0 || anyArgPresent(normalized, t.PathLastIfAny))
		forceLast := lastEnabled && i == len(normalized)-1 && arg != "-" && !strings.HasPrefix(arg, "-")
		v, err := pm.mapArg(arg, forceLast)
		if err != nil {
			return nil, nil, err
		}
		mapped[i] = v
	}
	if forceNext {
		return nil, nil, fmt.Errorf("tool %q: option %q requires a path argument", t.Name, normalized[len(normalized)-1])
	}
	return mapped, pm.mounts, nil
}

func (pm *pathMapper) mapArg(arg string, force bool) (string, error) {
	hostPath, isPath, err := resolveWindowsPathArgMode(pm.cwd, arg, force)
	if err != nil {
		return "", err
	}
	if !isPath {
		return arg, nil
	}
	if rel, ok := pathWithin(pm.root, hostPath); ok {
		if rel == "." {
			return pm.workspaceRoot, nil
		}
		return pm.workspaceRoot + "/" + filepath.ToSlash(rel), nil
	}
	mountRoot, err := externalMountRoot(hostPath)
	if err != nil {
		return "", fmt.Errorf("map argument path %q: %w", arg, err)
	}
	key := strings.ToLower(filepath.Clean(mountRoot))
	target, exists := pm.mountBySource[key]
	if !exists {
		target = fmt.Sprintf("/cb/mounts/%d", len(pm.mounts))
		pm.mountBySource[key] = target
		pm.mounts = append(pm.mounts, PathMount{mountRoot, target})
	}
	rel, err := filepath.Rel(mountRoot, hostPath)
	if err != nil {
		return "", err
	}
	if rel == "." {
		return target, nil
	}
	return target + "/" + filepath.ToSlash(rel), nil
}

func containsString(xs []string, s string) bool {
	for _, x := range xs {
		if x == s {
			return true
		}
	}
	return false
}

func anyArgPresent(args, needles []string) bool {
	for _, arg := range args {
		if containsString(needles, arg) {
			return true
		}
	}
	return false
}

func validEnvAssignment(s string) bool {
	i := strings.IndexByte(s, '=')
	if i <= 0 {
		return false
	}
	name := s[:i]
	for j, r := range name {
		if (r >= 'A' && r <= 'Z') || (r >= 'a' && r <= 'z') || r == '_' || (j > 0 && r >= '0' && r <= '9') {
			continue
		}
		return false
	}
	return true
}

func selectedHostEnv(t Tool) []string {
	if len(t.EnvNames) == 0 && len(t.EnvPrefixes) == 0 {
		return nil
	}
	exact := map[string]bool{}
	for _, n := range t.EnvNames {
		exact[strings.ToUpper(n)] = true
	}
	seen := map[string]bool{}
	var out []string
	for _, kv := range os.Environ() {
		name := strings.SplitN(kv, "=", 2)[0]
		upper := strings.ToUpper(name)
		match := exact[upper]
		if !match {
			for _, p := range t.EnvPrefixes {
				if strings.HasPrefix(upper, strings.ToUpper(p)) {
					match = true
					break
				}
			}
		}
		if match && !seen[upper] {
			seen[upper] = true
			out = append(out, name)
		}
	}
	sort.Strings(out)
	return out
}

// resolveWindowsPathArg recognizes the forms that can be mapped safely without
// knowing tool-specific argument grammar:
//
//	C:\foo\bar      absolute Windows path
//	.\foo / ..\foo explicit relative Windows path
//	subdir\foo      only when it already exists on the host
//
// Plain strings that merely contain backslashes are left untouched.
func resolveWindowsPathArg(cwd, arg string) (string, bool, error) {
	return resolveWindowsPathArgMode(cwd, arg, false)
}

func resolveWindowsPathArgMode(cwd, arg string, force bool) (string, bool, error) {
	if isWindowsAbsPath(arg) {
		p, err := canonicalPath(arg)
		if err != nil {
			return "", false, fmt.Errorf("canonicalize argument path %q: %w", arg, err)
		}
		return p, true, nil
	}
	if isExplicitWindowsRelPath(arg) || (force && !strings.HasPrefix(arg, "-") && arg != "") {
		p, err := canonicalPath(filepath.Join(cwd, arg))
		if err != nil {
			return "", false, fmt.Errorf("canonicalize relative argument path %q: %w", arg, err)
		}
		return p, true, nil
	}
	if strings.Contains(arg, `\`) && !strings.ContainsAny(arg, "\r\n\t") {
		candidate := filepath.Join(cwd, arg)
		if _, err := os.Stat(candidate); err == nil {
			p, err := canonicalPath(candidate)
			if err != nil {
				return "", false, err
			}
			return p, true, nil
		}
	}
	return "", false, nil
}
func isExplicitWindowsRelPath(s string) bool {
	return strings.HasPrefix(s, `.\`) || strings.HasPrefix(s, `..\`) ||
		strings.HasPrefix(s, "./") || strings.HasPrefix(s, "../")
}

func isWindowsAbsPath(s string) bool {
	if len(s) < 3 {
		return false
	}
	c := s[0]
	isLetter := (c >= 'A' && c <= 'Z') || (c >= 'a' && c <= 'z')
	return isLetter && s[1] == ':' && (s[2] == '\\' || s[2] == '/')
}

func pathWithin(root, p string) (string, bool) {
	rel, err := filepath.Rel(root, p)
	if err != nil {
		return "", false
	}
	if rel == ".." || strings.HasPrefix(rel, ".."+string(filepath.Separator)) || filepath.IsAbs(rel) {
		return "", false
	}
	return rel, true
}

func externalMountRoot(hostPath string) (string, error) {
	if st, err := os.Stat(hostPath); err == nil {
		if st.IsDir() {
			return hostPath, nil
		}
		return filepath.Dir(hostPath), nil
	} else if !os.IsNotExist(err) {
		return "", err
	}
	candidate := filepath.Dir(hostPath)
	for {
		if st, err := os.Stat(candidate); err == nil {
			if !st.IsDir() {
				return "", fmt.Errorf("nearest existing ancestor is not a directory: %s", candidate)
			}
			return candidate, nil
		} else if !os.IsNotExist(err) {
			return "", err
		}
		parent := filepath.Dir(candidate)
		if parent == candidate {
			return "", fmt.Errorf("no existing ancestor for %s", hostPath)
		}
		candidate = parent
	}
}

func mountSpec(kind, src, dst string) (string, error) {
	if strings.Contains(src, ",") {
		return "", fmt.Errorf("source path/volume contains a comma and cannot be represented safely in docker --mount syntax (values are comma-separated with no escaping): %s", src)
	}
	if strings.Contains(dst, ",") {
		return "", fmt.Errorf("destination path contains a comma and cannot be represented safely in docker --mount syntax (values are comma-separated with no escaping): %s", dst)
	}
	return fmt.Sprintf("type=%s,src=%s,dst=%s", kind, src, dst), nil
}

func workspaceRootFor(t Tool, root string) string {
	if t.Provider != "stateful" {
		return "/workspace"
	}
	base := filepath.Base(filepath.Clean(root))
	if base == "." || base == string(filepath.Separator) || base == "" {
		base = "project"
	}
	// Windows project names cannot contain '/', so this remains a single
	// container path segment while preserving the basename semantics tools
	// such as `npm init` observe.
	base = strings.ReplaceAll(base, "/", "_")
	return "/workspace/" + base
}

func statefulWorkspaceDestination(dst, workspaceRoot string) string {
	if dst == "/workspace" {
		return workspaceRoot
	}
	if strings.HasPrefix(dst, "/workspace/") {
		return workspaceRoot + strings.TrimPrefix(dst, "/workspace")
	}
	return dst
}

func projectMarkersFor(t Tool) []string {
	if len(t.ProjectMarkers) > 0 {
		return t.ProjectMarkers
	}
	// Backward compatibility for registries created before v0.6, whose
	// Python sections did not yet declare project_markers explicitly.
	if t.Provider == "python" {
		return []string{"pyproject.toml", "requirements.txt", "setup.py", "setup.cfg", ".git"}
	}
	return []string{".git"}
}

func findProjectRoot(start string, markers []string) (string, bool) {
	dir := start
	for {
		for _, marker := range markers {
			if _, err := os.Stat(filepath.Join(dir, marker)); err == nil {
				return dir, true
			}
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return "", false
		}
		dir = parent
	}
}

func parseVolumeBinding(spec string) (string, string, error) {
	i := strings.Index(spec, ":/")
	if i <= 0 {
		return "", "", errors.New("expected NAME:/absolute/container/path")
	}
	name, dst := spec[:i], spec[i+1:]
	if !validToolName(name) {
		return "", "", fmt.Errorf("invalid volume name %q", name)
	}
	if !strings.HasPrefix(dst, "/") {
		return "", "", errors.New("container path must be absolute")
	}
	return name, dst, nil
}

func volumeHash(root string) string {
	sum := sha256.Sum256([]byte(strings.ToLower(filepath.Clean(root))))
	return hex.EncodeToString(sum[:])[:12]
}

func statefulProjectVolumeID(group, name, root string, project bool) string {
	_ = project // root already falls back to cwd when no marker was found
	return "cb-" + group + "-" + name + "-" + volumeHash(root)
}

func statefulSharedVolumeID(group, name string) string { return "cb-" + group + "-" + name }

func canonicalPath(p string) (string, error) {
	abs, err := filepath.Abs(p)
	if err != nil {
		return "", err
	}
	if resolved, err := filepath.EvalSymlinks(abs); err == nil {
		abs = resolved
	}
	abs = filepath.Clean(abs)
	if runtime.GOOS == "windows" {
		abs = strings.ToLower(abs)
	}
	return abs, nil
}

func pythonEnvID(root string, project bool) string {
	if !project {
		return "cb-python-313-global"
	}
	return "cb-python-313-" + volumeHash(root)
}

