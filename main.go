func defaultRegistry() Registry {
	reg, err := parseRegistryTOML(defaultRegistryTOML)
	if err != nil {
		panic("invalid built-in registry: " + err.Error())
	}
	return reg
}

func registryPath() (string, error) {
	exe, err := os.Executable()
	if err != nil {
		return "", err
	}
	exe, err = filepath.Abs(exe)
	if err != nil {
		return "", err
	}
	return filepath.Join(filepath.Dir(exe), "container-bin.toml"), nil
}

func ensureRegistryFile(path string) error {
	if _, err := os.Stat(path); err == nil {
		return nil
	} else if !os.IsNotExist(err) {
		return err
	}
	return atomicWriteFile(path, []byte(defaultRegistryTOML), 0644)
}

// appendMissingDefaultTools upgrades an existing registry non-destructively.
// Existing tool sections are never rewritten; missing built-in sections are
// appended, preserving user profiles and comments (e.g. jq2 from earlier tests).
func appendMissingDefaultTools(path string) error {
	data, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	reg, err := parseRegistryTOML(string(data))
	if err != nil {
		return err
	}
	defaults := defaultToolSections()
	var names []string
	for name := range defaults {
		if _, exists := reg.Tools[name]; !exists {
			names = append(names, name)
		}
	}
	if len(names) == 0 {
		return nil
	}
	sort.Strings(names)
	var b strings.Builder
	b.Write(data)
	if len(data) > 0 && data[len(data)-1] != '\n' {
		b.WriteByte('\n')
	}
	b.WriteString("\n# Added by container-bin " + version + "\n")
	for _, name := range names {
		b.WriteString(defaults[name])
	}
	return atomicWriteFile(path, []byte(b.String()), 0644)
}

func defaultToolSections() map[string]string {
	sections := map[string]string{}
	var current string
	var b strings.Builder
	flush := func() {
		if current != "" {
			sections[current] = "\n" + b.String()
		}
		b.Reset()
	}
	for _, line := range strings.Split(defaultRegistryTOML, "\n") {
		trim := strings.TrimSpace(line)
		if strings.HasPrefix(trim, "[tools.") && strings.HasSuffix(trim, "]") {
			flush()
			current = strings.TrimSuffix(strings.TrimPrefix(trim, "[tools."), "]")
		}
		if current != "" {
			b.WriteString(line)
			b.WriteByte('\n')
		}
	}
	flush()
	return sections
}

func loadRegistry() (Registry, string, error) {
	path, err := registryPath()
	if err != nil {
		return Registry{}, "", err
	}
	data, err := os.ReadFile(path)
	if os.IsNotExist(err) {
		rec, err := recoverFromBackup(path, validateRegistryBackup)
		if err != nil {
			return Registry{}, path, err
		}
		if !rec {
			return defaultRegistry(), path, nil
		}
		data, err = os.ReadFile(path)
		if err != nil {
			return Registry{}, path, err
		}
	} else if err != nil {
		return Registry{}, path, err
	}
	reg, err := parseRegistryTOML(string(data))
	return reg, path, err
}

// parseRegistryTOML intentionally supports only the tiny TOML subset used by
// container-bin's registry: [tools.NAME], quoted strings and arrays of quoted
// strings. Rejecting unknown syntax is safer than silently misreading config.
func parseRegistryTOML(s string) (Registry, error) {
	reg := Registry{SchemaVersion: 1, Tools: map[string]Tool{}}
	var current *Tool
	scanner := bufio.NewScanner(strings.NewReader(s))
	lineNo := 0
	for scanner.Scan() {
		lineNo++
		line := strings.TrimSpace(stripComment(scanner.Text()))
		if line == "" {
			continue
		}
		if strings.HasPrefix(line, "[") {
			if !strings.HasSuffix(line, "]") {
				return reg, fmt.Errorf("line %d: malformed section", lineNo)
			}
			sec := strings.TrimSpace(line[1 : len(line)-1])
			if !strings.HasPrefix(sec, "tools.") || len(sec) <= len("tools.") {
				return reg, fmt.Errorf("line %d: only [tools.NAME] sections are supported", lineNo)
			}
			name := strings.ToLower(strings.TrimSpace(strings.TrimPrefix(sec, "tools.")))
			if !validToolName(name) {
				return reg, fmt.Errorf("line %d: invalid tool name %q", lineNo, name)
			}
			if reservedToolName(name) {
				return reg, fmt.Errorf("line %d: tool name %q is reserved (would collide with cb itself or a Windows device name); rename or delete the [tools.%s] section in the registry file to recover", lineNo, name, name)
			}
			if _, dup := reg.Tools[name]; dup {
				return reg, fmt.Errorf("line %d: duplicate [tools.%s] section", lineNo, name)
			}
			t := Tool{Name: name, Provider: "stateless"}
			reg.Tools[name] = t
			current = &t
			continue
		}
		if current == nil {
			kv := strings.SplitN(line, "=", 2)
			if len(kv) == 2 && strings.TrimSpace(kv[0]) == "schema_version" {
				v, err := strconv.Atoi(strings.TrimSpace(kv[1]))
				if err != nil || v < 1 {
					return reg, fmt.Errorf("line %d: invalid schema_version", lineNo)
				}
				if v > 1 {
					return reg, fmt.Errorf("line %d: registry schema_version %d is newer than this cb supports (max 1)", lineNo, v)
				}
				reg.SchemaVersion = v
				continue
			}
			return reg, fmt.Errorf("line %d: key outside [tools.NAME] section", lineNo)
		}
		kv := strings.SplitN(line, "=", 2)
		if len(kv) != 2 {
			return reg, fmt.Errorf("line %d: expected key = value", lineNo)
		}
		key := strings.TrimSpace(kv[0])
		value := strings.TrimSpace(kv[1])
		t := reg.Tools[current.Name]
		switch key {
		case "image":
			v, err := parseQuoted(value)
			if err != nil {
				return reg, fmt.Errorf("line %d image: %w", lineNo, err)
			}
			t.Image = v
		case "provider":
			v, err := parseQuoted(value)
			if err != nil {
				return reg, fmt.Errorf("line %d provider: %w", lineNo, err)
			}
			t.Provider = strings.ToLower(v)
		case "role":
			v, err := parseQuoted(value)
			if err != nil {
				return reg, fmt.Errorf("line %d role: %w", lineNo, err)
			}
			t.Role = strings.ToLower(v)
		case "command":
			v, err := parseStringArray(value)
			if err != nil {
				return reg, fmt.Errorf("line %d command: %w", lineNo, err)
			}
			t.Command = v
		case "args_prefix":
			v, err := parseStringArray(value)
			if err != nil {
				return reg, fmt.Errorf("line %d args_prefix: %w", lineNo, err)
			}
			t.ArgsPrefix = v
		case "path_next":
			v, err := parseStringArray(value)
			if err != nil {
				return reg, fmt.Errorf("line %d path_next: %w", lineNo, err)
			}
			t.PathNext = v
		case "path_equals":
			v, err := parseStringArray(value)
			if err != nil {
				return reg, fmt.Errorf("line %d path_equals: %w", lineNo, err)
			}
			t.PathEquals = v
		case "path_last":
			v, err := parseBool(value)
			if err != nil {
				return reg, fmt.Errorf("line %d path_last: %w", lineNo, err)
			}
			t.PathLast = v
		case "path_last_if_any":
			v, err := parseStringArray(value)
			if err != nil {
				return reg, fmt.Errorf("line %d path_last_if_any: %w", lineNo, err)
			}
			t.PathLastIfAny = v
		case "env_prefixes":
			v, err := parseStringArray(value)
			if err != nil {
				return reg, fmt.Errorf("line %d env_prefixes: %w", lineNo, err)
			}
			t.EnvPrefixes = v
		case "env_names":
			v, err := parseStringArray(value)
			if err != nil {
				return reg, fmt.Errorf("line %d env_names: %w", lineNo, err)
			}
			t.EnvNames = v
		case "env_set":
			v, err := parseStringArray(value)
			if err != nil {
				return reg, fmt.Errorf("line %d env_set: %w", lineNo, err)
			}
			for _, kv := range v {
				if !validEnvAssignment(kv) {
					return reg, fmt.Errorf("line %d env_set: invalid NAME=VALUE %q", lineNo, kv)
				}
			}
			t.EnvSet = v
		case "project_markers":
			v, err := parseStringArray(value)
			if err != nil {
				return reg, fmt.Errorf("line %d project_markers: %w", lineNo, err)
			}
			t.ProjectMarkers = v
		case "state_group":
			v, err := parseQuoted(value)
			if err != nil {
				return reg, fmt.Errorf("line %d state_group: %w", lineNo, err)
			}
			t.StateGroup = strings.ToLower(v)
		case "project_volumes":
			v, err := parseStringArray(value)
			if err != nil {
				return reg, fmt.Errorf("line %d project_volumes: %w", lineNo, err)
			}
			t.ProjectVolumes = v
		case "shared_volumes":
			v, err := parseStringArray(value)
			if err != nil {
				return reg, fmt.Errorf("line %d shared_volumes: %w", lineNo, err)
			}
			t.SharedVolumes = v
		default:
			return reg, fmt.Errorf("line %d: unsupported key %q", lineNo, key)
		}
		reg.Tools[current.Name] = t
		*current = t
	}
	if err := scanner.Err(); err != nil {
		return reg, err
	}
	if len(reg.Tools) == 0 {
		return reg, errors.New("registry contains no tools")
	}
	for name, t := range reg.Tools {
		if t.Image == "" {
			return reg, fmt.Errorf("tool %q: image is required", name)
		}
		switch t.Provider {
		case "stateless":
		case "python":
			if t.Role != "python" && t.Role != "pip" {
				return reg, fmt.Errorf("tool %q: python provider requires role = \"python\" or \"pip\"", name)
			}
		case "stateful":
			if t.StateGroup == "" {
				return reg, fmt.Errorf("tool %q: stateful provider requires state_group", name)
			}
			if len(t.ProjectVolumes) == 0 && len(t.SharedVolumes) == 0 {
				return reg, fmt.Errorf("tool %q: stateful provider requires at least one volume", name)
			}
			for _, spec := range append(append([]string{}, t.ProjectVolumes...), t.SharedVolumes...) {
				if _, _, err := parseVolumeBinding(spec); err != nil {
					return reg, fmt.Errorf("tool %q volume %q: %w", name, spec, err)
				}
			}
		default:
			return reg, fmt.Errorf("tool %q: unsupported provider %q", name, t.Provider)
		}
	}
	return reg, nil
}

func stripComment(s string) string {
	inQuote := false
	escaped := false
	for i, r := range s {
		if escaped {
			escaped = false
			continue
		}
		if r == '\\' && inQuote {
			escaped = true
			continue
		}
		if r == '"' {
			inQuote = !inQuote
			continue
		}
		if r == '#' && !inQuote {
			return s[:i]
		}
	}
	return s
}

func parseQuoted(s string) (string, error) {
	s = strings.TrimSpace(s)
	if len(s) < 2 || s[0] != '"' || s[len(s)-1] != '"' {
		return "", errors.New("expected quoted string")
	}
	v, err := strconv.Unquote(s)
	if err != nil {
		return "", err
	}
	return v, nil
}

func parseBool(s string) (bool, error) {
	switch strings.TrimSpace(s) {
	case "true":
		return true, nil
	case "false":
		return false, nil
	default:
		return false, errors.New("expected true or false")
	}
}

func parseStringArray(s string) ([]string, error) {
	s = strings.TrimSpace(s)
	if s == "[]" {
		return nil, nil
	}
	if len(s) < 2 || s[0] != '[' || s[len(s)-1] != ']' {
		return nil, errors.New("expected array of quoted strings")
	}
	inner := strings.TrimSpace(s[1 : len(s)-1])
	var out []string
	for len(inner) > 0 {
		inner = strings.TrimSpace(inner)
		if !strings.HasPrefix(inner, "\"") {
			return nil, errors.New("array elements must be quoted strings")
		}
		end := -1
		escaped := false
		for i := 1; i < len(inner); i++ {
			if escaped {
				escaped = false
				continue
			}
			if inner[i] == '\\' {
				escaped = true
				continue
			}
			if inner[i] == '"' {
				end = i
				break
			}
		}
		if end < 0 {
			return nil, errors.New("unterminated string")
		}
		v, err := strconv.Unquote(inner[:end+1])
		if err != nil {
			return nil, err
		}
		out = append(out, v)
		inner = strings.TrimSpace(inner[end+1:])
		if inner == "" {
			break
		}
		if inner[0] != ',' {
			return nil, errors.New("expected comma between array elements")
		}
		inner = inner[1:]
	}
	return out, nil
}

func validToolName(s string) bool {
	if s == "" {
		return false
	}
	for _, r := range s {
		if (r >= 'a' && r <= 'z') || (r >= '0' && r <= '9') || r == '-' || r == '_' {
			continue
		}
		return false
	}
	return true
}

// reservedToolName rejects names whose NAME.exe shim would collide with the
// cb binary itself, or which are Windows reserved device names (creating
// con.exe / nul.exe etc. misbehaves across Windows tooling).
func reservedToolName(s string) bool {
	switch s {
	case "cb", "container-bin", "con", "prn", "aux", "nul":
		return true
	}
	// main() treats any argv[0] starting with "cb-v" as the management CLI
	// (versioned binary names), so such a shim could never dispatch to a tool.
	if strings.HasPrefix(s, "cb-v") {
		return true
	}
	if len(s) == 4 && (strings.HasPrefix(s, "com") || strings.HasPrefix(s, "lpt")) && s[3] >= '1' && s[3] <= '9' {
		return true
	}
	return false
}

